// Retro format definitions: banlist + card pool cutoff date
// Each format uses the TCG banlist in effect on the given date.

// ── Shared helpers ──────────────────────────────────────────────────────────

function mkFormat({ id, label, cutoffDate, forbidden, limited, semiLimited }) {
  const f = new Set(forbidden);
  const l = new Set(limited);
  const sl = new Set(semiLimited);
  return {
    id,
    label,
    cutoffDate: new Date(cutoffDate),
    getStatus(cardName, tcgDate) {
      if (f.has(cardName)) return "forbidden";
      if (l.has(cardName)) return "limited";
      if (sl.has(cardName)) return "semi-limited";
      if (tcgDate) {
        const d = new Date(tcgDate);
        if (d >= this.cutoffDate) return "not-legal";
      }
      return "unlimited";
    },
    maxCopies(cardName) {
      if (f.has(cardName)) return 0;
      if (l.has(cardName)) return 1;
      if (sl.has(cardName)) return 2;
      return 3;
    },
  };
}

